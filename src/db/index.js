import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { AsyncLocalStorage } from 'node:async_hooks';
import { DatabaseSync } from 'node:sqlite';
import { recursos } from '../resources.js';
import { conectarSupabase, conectarPglite } from './postgres.js';

// Capa de datos asíncrona. Todo el resto del código habla con la base por esta
// misma forma, sin saber si detrás hay SQLite (local) o Postgres (Supabase):
//
//   await db.todos(sql, params)      → filas
//   await db.uno(sql, params)        → una fila o undefined
//   await db.ejecutar(sql, params)   → { cambios, id }
//   await db.exec(sql)               → DDL o varias sentencias
//   await db.transaccion(async () => …)
//
// El SQL se escribe con `?`; el adaptador de Postgres lo traduce.

// Marca el contexto asíncrono que está dentro de una transacción. Así, una
// consulta hecha desde adentro corre en la transacción en vez de quedarse
// esperando a que termine, que sería esperarse a sí misma.
const dentroDeTx = new AsyncLocalStorage();

class Sqlite {
  motor = 'sqlite';
  #raw;
  #enCurso = null; // promesa de la transacción abierta, si hay una

  constructor(raw) {
    this.#raw = raw;
  }

  // Las sentencias de afuera esperan a que cierre la transacción abierta: con
  // una sola conexión, si no esperaran quedarían metidas dentro de ella.
  async #turno() {
    if (dentroDeTx.getStore() === this) return;
    while (this.#enCurso) await this.#enCurso;
  }

  async todos(sql, params = []) {
    await this.#turno();
    return this.#raw.prepare(sql).all(...params);
  }

  async uno(sql, params = []) {
    await this.#turno();
    return this.#raw.prepare(sql).get(...params);
  }

  async ejecutar(sql, params = []) {
    await this.#turno();
    const r = this.#raw.prepare(sql).run(...params);
    return { cambios: Number(r.changes), id: Number(r.lastInsertRowid) };
  }

  async exec(sql) {
    await this.#turno();
    this.#raw.exec(sql);
  }

  async transaccion(fn) {
    // Anidada: se suma a la que ya está abierta.
    if (dentroDeTx.getStore() === this) return fn(this);
    await this.#turno();

    let liberar;
    this.#enCurso = new Promise((ok) => { liberar = ok; });
    try {
      return await dentroDeTx.run(this, async () => {
        this.#raw.exec('BEGIN');
        try {
          const r = await fn(this);
          this.#raw.exec('COMMIT');
          return r;
        } catch (e) {
          this.#raw.exec('ROLLBACK');
          throw e;
        }
      });
    } finally {
      this.#enCurso = null;
      liberar();
    }
  }

  async columnas(tabla) {
    const filas = await this.todos(`PRAGMA table_info("${tabla}")`);
    return new Set(filas.map((c) => c.name));
  }

  // Copia consistente con VACUUM INTO: SQLite escribe un archivo nuevo sin
  // detener el servidor, y sin el riesgo de copiar el WAL a medias.
  async vaciarEn(destino) {
    await this.#turno();
    this.#raw.prepare('VACUUM INTO ?').run(destino);
  }

  async cerrar() {
    this.#raw.close();
  }
}

// ---------- Esquema ----------

const DIALECTO = {
  sqlite: {
    tipo: { texto: 'TEXT', fecha: 'TEXT', fechahora: 'TEXT', opcion: 'TEXT', json: 'TEXT', entero: 'INTEGER', ref: 'INTEGER', real: 'REAL' },
    id: 'id INTEGER PRIMARY KEY AUTOINCREMENT',
    ahora: "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))",
  },
  postgres: {
    // NUMERIC y no DOUBLE PRECISION: con plata y kilos no se quiere el error de
    // redondeo binario, y ROUND(x, 1) en Postgres solo existe para NUMERIC.
    tipo: { texto: 'TEXT', fecha: 'TEXT', fechahora: 'TEXT', opcion: 'TEXT', json: 'TEXT', entero: 'INTEGER', ref: 'INTEGER', real: 'NUMERIC' },
    // BY DEFAULT y no ALWAYS: al pasar los datos de la base local se conservan
    // los ids de cada registro, para no romper las referencias entre tablas.
    id: 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    // Mismo formato que el de SQLite: 2026-10-22T14:25:13.123Z
    ahora: `(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`,
  },
};

function columnaSql(dialecto, nombre, def) {
  let sql = `"${nombre}" ${dialecto.tipo[def.tipo]}`;
  if (def.tipo === 'ref') sql += ` REFERENCES "${def.ref}"(id)`;
  return sql;
}

// Huella del modelo de datos. En línea cada función arranca en frío, y revisar
// tabla por tabla en cada arranque son decenas de viajes a la base: si la
// huella guardada coincide, no hay nada que migrar. VERSION entra en la huella
// para que un cambio en cómo se migra (no solo en el modelo) vuelva a correr.
const VERSION = 2; // 2: tablas cerradas a la API pública de Supabase

function huellaDelModelo() {
  const modelo = Object.entries(recursos).map(([t, r]) => [t, r.campos, r.unico ?? null, r.campoFecha ?? null]);
  return crypto.createHash('sha256').update(JSON.stringify([VERSION, modelo])).digest('hex').slice(0, 16);
}

// Supabase publica por su API toda tabla del esquema public, y la clave
// publicable está hecha para ir dentro de páginas web. Sin esto, cualquiera con
// esa clave podría leer y cambiar la contabilidad. Seguridad de filas (RLS) sin
// ninguna política cierra la API por completo; el sistema entra como dueño de
// las tablas y no lo afecta. Además se quitan los permisos a los roles de la API
// (anon, authenticated), que solo existen en Supabase.
async function cerrarALaApi(db, tabla) {
  if (db.motor !== 'postgres') return;
  await db.exec(`ALTER TABLE "${tabla}" ENABLE ROW LEVEL SECURITY`);
  await db.exec(`DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
      EXECUTE 'REVOKE ALL ON TABLE "${tabla}" FROM anon, authenticated';
    END IF;
  END $$`);
}

// Crea tablas nuevas y agrega columnas nuevas sin tocar los datos existentes.
// Suficiente mientras el modelo solo crece; renombrar/eliminar columnas requiere
// una migración manual.
export async function migrar(db) {
  const huella = huellaDelModelo();
  try {
    const guardada = await db.uno('SELECT huella FROM esquema_version');
    if (guardada?.huella === huella) return false;
  } catch { /* la tabla todavía no existe: base nueva */ }

  const d = DIALECTO[db.motor];

  // Respuestas de servicios externos (pronóstico, climatología, ENSO) para no
  // repetir consultas y poder mostrar el último dato sin conexión.
  await db.exec(`CREATE TABLE IF NOT EXISTS cache_externo (
    clave TEXT PRIMARY KEY,
    datos TEXT NOT NULL,
    obtenido_en TEXT NOT NULL
  )`);
  await cerrarALaApi(db, 'cache_externo');

  for (const [tabla, rec] of Object.entries(recursos)) {
    const columnas = Object.entries(rec.campos).map(([n, def]) => columnaSql(d, n, def));
    await db.exec(`CREATE TABLE IF NOT EXISTS "${tabla}" (
      ${d.id},
      ${columnas.join(',\n      ')},
      creado_en TEXT NOT NULL DEFAULT ${d.ahora},
      actualizado_en TEXT NOT NULL DEFAULT ${d.ahora}
    )`);
    await cerrarALaApi(db, tabla);

    const existentes = await db.columnas(tabla);
    for (const [n, def] of Object.entries(rec.campos)) {
      if (!existentes.has(n)) await db.exec(`ALTER TABLE "${tabla}" ADD COLUMN ${columnaSql(d, n, def)}`);
    }

    for (const [n, def] of Object.entries(rec.campos)) {
      if (def.tipo === 'ref') await db.exec(`CREATE INDEX IF NOT EXISTS "ix_${tabla}_${n}" ON "${tabla}"("${n}")`);
    }
    if (rec.campoFecha) {
      await db.exec(`CREATE INDEX IF NOT EXISTS "ix_${tabla}_${rec.campoFecha}" ON "${tabla}"("${rec.campoFecha}")`);
    }
    if (rec.unico) {
      const cols = rec.unico.map((c) => `"${c}"`).join(', ');
      await db.exec(`CREATE UNIQUE INDEX IF NOT EXISTS "ux_${tabla}" ON "${tabla}"(${cols})`);
    }
  }

  await db.exec('CREATE TABLE IF NOT EXISTS esquema_version (huella TEXT NOT NULL)');
  await cerrarALaApi(db, 'esquema_version');
  await db.ejecutar('DELETE FROM esquema_version');
  await db.ejecutar('INSERT INTO esquema_version (huella) VALUES (?)', [huella]);
  return true;
}

// ---------- Abrir ----------

async function abrirSqlite(ruta) {
  if (ruta !== ':memory:') fs.mkdirSync(path.dirname(ruta), { recursive: true });
  const raw = new DatabaseSync(ruta);
  raw.exec('PRAGMA foreign_keys = ON');
  if (ruta !== ':memory:') raw.exec('PRAGMA journal_mode = WAL');
  return new Sqlite(raw);
}

// El destino decide el motor:
//   postgres://… o postgresql://…  → Supabase (en línea)
//   pglite:memoria | pglite:<carpeta> → Postgres dentro de Node (pruebas)
//   cualquier otra cosa              → archivo SQLite, o :memory:
export async function abrirDb(destino) {
  let db;
  if (/^postgres(ql)?:\/\//.test(destino)) db = await conectarSupabase(destino);
  else if (destino.startsWith('pglite:')) db = await conectarPglite(destino.slice('pglite:'.length));
  else db = await abrirSqlite(destino);
  await migrar(db);
  return db;
}

// ---------- Respaldo ----------

// Toda la base en un archivo .sqlite, sea cual sea el motor. Desde SQLite es
// una copia directa; desde Postgres se copian las tablas a un SQLite nuevo,
// dentro de una transacción para que la foto sea de un solo instante. Así el
// respaldo se abre igual con cualquier herramienta de SQLite y sirve para
// volver a levantar el sistema en local aunque Supabase no esté.
export async function respaldar(db, destino) {
  if (db.motor === 'sqlite') return db.vaciarEn(destino);

  const copia = await abrirSqlite(destino);
  try {
    await migrar(copia);
    const tablas = ['cache_externo', ...Object.keys(recursos)];
    await db.transaccion(async () => {
      for (const tabla of tablas) {
        const filas = await db.todos(`SELECT * FROM "${tabla}"`);
        if (!filas.length) continue;
        const cols = Object.keys(filas[0]);
        const insertar = `INSERT INTO "${tabla}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${cols.map(() => '?').join(', ')})`;
        await copia.transaccion(async () => {
          for (const f of filas) await copia.ejecutar(insertar, cols.map((c) => f[c]));
        });
      }
    });
  } finally {
    await copia.cerrar();
  }
}
